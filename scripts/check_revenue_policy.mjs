import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createSalesView} from '../public/sales-view.js';
const a=JSON.parse(fs.readFileSync(new URL('../public/analysis-data.json',import.meta.url)));
const b=JSON.parse(fs.readFileSync(new URL('../public/data.json',import.meta.url)));
const channels={...JSON.parse(fs.readFileSync(new URL('../public/channel-data.json',import.meta.url))),direct:JSON.parse(fs.readFileSync(new URL('../public/direct-delivery.json',import.meta.url)))};
const nf=n=>Math.round(n).toLocaleString('ko-KR'),iso=d=>d.toISOString().slice(0,10),date=s=>new Date(s+'T00:00:00Z');
globalThis.location={hash:'#dashboard?scope=pos'};
const view=createSalesView({getAnalysis:()=>a,getChannels:()=>channels,getRows:()=>b.daily,read:(k,d)=>d,today:'2026-11-05',
  sum:(rs,k)=>rs.reduce((n,r)=>n+(r[k]??0),0),date,iso,add:(s,n)=>iso(new Date(+date(s)+n*86400000)),esc:String,nf,won:n=>'₩'+nf(n)});
const html=view.render();
assert.ok(html.includes('₩8,826,500'),'Default month uses reconciled channel ledger');
assert.ok(!html.includes('₩76,231,800'),'POS product total cannot replace store total');
assert.ok(!html.includes('₩803,858,280'),'POS annual total cannot replace store annual total');
assert.ok(html.includes('₩879,376,180')&&!html.includes('연 누계 아님'));
assert.ok(html.includes('페이히어 + 오터 + 네이버'));
assert.ok(html.includes('원본 채널 합계 = 표시 총매출'),'Reconciled originals must equal the headline');
assert.ok(html.includes('7,027,000')&&html.includes('37,600')&&html.includes('1,761,900'));
assert.ok(!html.includes('<select id="salesScope"'),'Store revenue cannot switch to POS-only scope');
