import assert from 'node:assert/strict';
import fs from 'node:fs';
import {weeklyOptionSource,rankOptions,optionFamily,renderWeeklyOptions} from '../dist/weekly-options.js';
import {createProductCatalog} from '../dist/product-catalog.js';
import {dateRange} from '../dist/weekly-view.js';
const a=JSON.parse(fs.readFileSync(new URL('../dist/analysis-data.json',import.meta.url)));
const catalog=createProductCatalog(JSON.parse(fs.readFileSync(new URL('../dist/product-master.json',import.meta.url))));
const current=weeklyOptionSource(a,dateRange('2026-10-19','2026-10-25'),catalog);
const previous=weeklyOptionSource(a,dateRange('2026-10-12','2026-10-18'),catalog);
assert.equal(current.complete,true);assert.equal(current.rows.length,305);
const gelato=rankOptions(current,previous,r=>optionFamily(r)==='gelato');
assert.equal(gelato.length>=17,true);
const rawCount=a.options.filter(r=>r.start==='2026-10-19'&&r.category==='젤라또').reduce((s,r)=>s+r.selections,0);
assert.equal(gelato.reduce((s,r)=>s+r.current,0),rawCount);
const cherry=gelato.find(r=>r.name==='Amarena Cherry');assert.equal(cherry.current,17);
const half=current.rows.filter(r=>/하프 앤 하프$/.test(r.name));
assert.equal(half.reduce((s,r)=>s+r.selections,0),14,'7 half-and-half pizzas have 14 menu selections');
const unavailable=weeklyOptionSource(a,dateRange('2026-10-05','2026-10-11'),catalog);
assert.equal(unavailable.complete,false);assert.equal(unavailable.rows.length,0);
assert(rankOptions(current,unavailable).every(r=>r.previous===null),'Missing source is never zero');
assert.equal(weeklyOptionSource(a,dateRange('2026-10-19','2026-10-21'),catalog).rows.length,0,'Never prorate a full week into a partial week');
const fixture={importSources:[{id:'old',kind:'options',start:'2026-07-01',end:'2026-10-28',complete:true}],options:[{source:'old',start:'2026-07-01',end:'2026-10-28',selections:10000}]};
assert.equal(weeklyOptionSource(fixture,dateRange('2026-10-19','2026-10-25')).rows.length,0);
const html=renderWeeklyOptions({active:dateRange('2026-10-19','2026-10-25'),prev:dateRange('2026-10-12','2026-10-18'),a:a.products.filter(r=>r.date>='2026-10-19'&&r.date<='2026-10-25').map(catalog.row)},{getAnalysis:()=>a,catalog:()=>catalog,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;'),nf:n=>n.toLocaleString('ko-KR'),won:n=>'₩'+n.toLocaleString('ko-KR')});
assert(html.includes('플레이버별 선택량 순위'));assert(html.includes('하프 앤 하프'));assert(html.includes('피자 &amp; 맥주 세트'));
assert(!html.includes('NaN'));assert(!html.includes('undefined'));
console.log(JSON.stringify({week:current.start,sourceRows:current.rows.length,flavors:gelato.length,flavorSelections:rawCount,halfSelections:14,previousAvailable:previous.complete}));
